/** «300 г» → «300 g» и т. п.: число остаётся, единица переводится */
export function localizeWeight(w: string, d: Dict): string {
  return w.replace(/(шт\.|кг|мл|г|л)$/u, (u) => d.units[u] ?? u);
}
